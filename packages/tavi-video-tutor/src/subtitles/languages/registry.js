/**
 * Authoritatively normalizes any language representation (ISO 639-1, ISO 639-2/3,
 * BCP-47, English name, or native name) into the canonical internal code.
 * 
 * @param {string} input 
 * @returns {string|null} Canonical language code (e.g. 'hi', 'en') or null if unrecognized
 */
export const normalizeLanguageCode = (input) => {
  if (!input || typeof input !== 'string') return null;
  const raw = input.trim().toLowerCase();
  if (!raw) return null;

  // Exact alias match
  if (ALIAS_TO_CODE.has(raw)) {
    return ALIAS_TO_CODE.get(raw);
  }

  // Handle locale suffix (e.g., 'hi-in', 'hi_in' -> 'hi')
  const basePrefix = raw.split(/[-_]/)[0];
  if (basePrefix && ALIAS_TO_CODE.has(basePrefix)) {
    return ALIAS_TO_CODE.get(basePrefix);
  }

  return null;
};

/**
 * Resolves a language entry by code, alias, name, or locale.
 * 
 * @param {string} code 
 * @returns {Object|null}
 */
export const getLanguageByCode = (code) => {
  if (!code) return null;
  const canonical = normalizeLanguageCode(code);
  if (!canonical) return null;
  return CODE_TO_LANG.get(canonical) || null;
};

/**
 * Resolves comprehensive language capabilities across translation, TTS,
 * and voice allocations.
 * 
 * @param {string} code 
 * @returns {Object}
 */
export const resolveLanguageCapability = (code) => {
  const canonical = normalizeLanguageCode(code);
  if (!canonical) {
    return {
      languageId: String(code || '').toLowerCase(),
      canonicalCode: null,
      normalizedCode: null,
      displayName: null,
      supported: false,
      translationSupported: false,
      translationSupport: false,
      ttsSupported: false,
      ttsSupport: false,
      speakerAwareCapability: false,
      subtitleCapability: false,
      error: 'UNSUPPORTED_LANGUAGE'
    };
  }

  const meta = CODE_TO_LANG.get(canonical);

  // Standard TTS voice and locale resolution
  const ttsLocale = meta.bcp47 || `${canonical}-${canonical.toUpperCase()}`;
  const translationCode = canonical;
  const voiceId = `${canonical}_voice_1`;

  return {
    languageId: canonical,
    canonicalCode: canonical,
    normalizedCode: canonical,
    displayName: meta.name,
    nativeName: meta.nativeName,
    iso639_2: meta.iso639_2,
    bcp47: meta.bcp47,
    ttsLocale,
    voiceLocale: ttsLocale,
    translationCode,
    translationProvider: 'mymemory',
    translationFallbackProvider: 'nllb',
    voiceId,
    supported: true,
    translationSupported: true,
    translationSupport: true,
    ttsProvider: 'node-tts',
    ttsSupported: true,
    ttsSupport: true,
    speakerAwareCapability: true,
    subtitleCapability: true,
    preferredVoices: {
      female: [`${canonical}_voice_1`, `${ttsLocale}-Female`],
      male: [`${canonical}_voice_2`, `${ttsLocale}-Male`]
    }
  };
};

/**
 * Programmatically returns capability matrix for all registered languages.
 * Dynamically reads the registry without hardcoding language count.
 * 
 * @returns {Array<Object>}
 */
export const getAllLanguageCapabilities = () => {
  return AITUTOR_LANGUAGES.map(lang => resolveLanguageCapability(lang.code));
};

