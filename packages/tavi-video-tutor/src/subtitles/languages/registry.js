// Build high-performance lookup maps for O(1) canonical resolution
const ALIAS_TO_CODE = new Map();
const CODE_TO_LANG = new Map();

for (const lang of AITUTOR_LANGUAGES) {
  CODE_TO_LANG.set(lang.code, lang);

  // 1. Direct code
  ALIAS_TO_CODE.set(lang.code.toLowerCase(), lang.code);

  // 2. ISO 639-2/3
  if (lang.iso639_2) {
    ALIAS_TO_CODE.set(lang.iso639_2.toLowerCase(), lang.code);
  }

  // 3. Full BCP-47 and lowercased variants
  if (lang.bcp47) {
    ALIAS_TO_CODE.set(lang.bcp47.toLowerCase(), lang.code);
    ALIAS_TO_CODE.set(lang.bcp47.toLowerCase().replace('-', '_'), lang.code);
  }

  // 4. English name and clean alphanumeric name
  ALIAS_TO_CODE.set(lang.name.toLowerCase(), lang.code);
  const cleanName = lang.name.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (cleanName) ALIAS_TO_CODE.set(cleanName, lang.code);

  // 5. Native Name
  ALIAS_TO_CODE.set(lang.nativeName.toLowerCase(), lang.code);
}

